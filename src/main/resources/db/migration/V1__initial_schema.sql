-- V1: TokenGate ka initial schema (jo pehle Hibernate ddl-auto banata tha)

CREATE TABLE teams (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(50)              NOT NULL UNIQUE,
    api_key_hash     VARCHAR(64)              NOT NULL UNIQUE,
    api_key_prefix   VARCHAR(12)              NOT NULL,
    active           BOOLEAN                  NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    daily_budget_usd NUMERIC(12, 6)
);

CREATE TABLE usage_records (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          VARCHAR(36)              NOT NULL UNIQUE,
    team_id           BIGINT                   NOT NULL,
    team_name         VARCHAR(50)              NOT NULL,
    provider          VARCHAR(30)              NOT NULL,
    model             VARCHAR(100)             NOT NULL,
    prompt_tokens     INTEGER                  NOT NULL,
    completion_tokens INTEGER                  NOT NULL,
    total_tokens      INTEGER                  NOT NULL,
    cost_usd          NUMERIC(18, 10)          NOT NULL,
    latency_ms        BIGINT                   NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_usage_team_time ON usage_records (team_id, created_at);

CREATE TABLE budget_alerts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id           BIGINT                   NOT NULL,
    team_name         VARCHAR(50)              NOT NULL,
    alert_date        DATE                     NOT NULL,
    threshold_percent INTEGER                  NOT NULL,
    spent_usd         NUMERIC(18, 10)          NOT NULL,
    budget_usd        NUMERIC(12, 6)           NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_alert_team_day_threshold UNIQUE (team_id, alert_date, threshold_percent)
);