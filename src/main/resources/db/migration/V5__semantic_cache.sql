-- V5: semantic cache (pgvector)
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE semantic_cache (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id       BIGINT        NOT NULL REFERENCES teams (id),
    model         VARCHAR(100)  NOT NULL,
    context_hash  VARCHAR(64)   NOT NULL,
    prompt_text   VARCHAR(4000) NOT NULL,
    embedding     vector(768)   NOT NULL,
    response_json TEXT          NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_semcache_lookup ON semantic_cache (team_id, model, context_hash);
CREATE INDEX idx_semcache_embedding ON semantic_cache USING hnsw (embedding vector_cosine_ops);

ALTER TABLE teams ADD COLUMN semantic_cache_enabled BOOLEAN NOT NULL DEFAULT FALSE;